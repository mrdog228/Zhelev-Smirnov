"use strict";

let hp = Number(prompt("Сколько увас hp?"));

hp += 40;
alert(`Вы подобрали аптечку, ваш запас hp теперь ${hp}`);

hp *= 2;
alert(`Сработал алтарь усиления, ваш запас hp теперь ${hp}`);

hp -= 50;
alert(`Вы наступили на ловушку, ваш запас hp теперь ${hp}`);

hp++;
alert(`Сработала регенерация, ваш запас hp теперь ${hp}`);

